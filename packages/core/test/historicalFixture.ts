export function historicalBtc15m(): Candle[] {
  return RAW.trim()
    .split("\n")
    .map((row) => {
      const [openTime, open, high, low, close, volume] = row
        .split(",")
        .map(Number);
      return {
        symbol: BTC_HISTORY_SOURCE.instrument,
        timeframe: BTC_HISTORY_SOURCE.timeframe,
        openTime: openTime!,
        closeTime: openTime! + 15 * 60_000 - 1,
        open: open!,
        high: high!,
        low: low!,
        close: close!,
        volume: volume!,
        closed: true,
      };
    });
}

export function aggregateCandles(
  candles: readonly Candle[],
  timeframe: Timeframe,
  groupSize: number,
): Candle[] {
  const result: Candle[] = [];
  for (let index = 0; index + groupSize <= candles.length; index += groupSize) {
    const group = candles.slice(index, index + groupSize);
    const first = group[0]!;
    const last = group.at(-1)!;
    result.push({
      symbol: first.symbol,
      timeframe,
      openTime: first.openTime,
      closeTime: last.closeTime,
      open: first.open,
      high: Math.max(...group.map((item) => item.high)),
      low: Math.min(...group.map((item) => item.low)),
      close: last.close,
      volume: group.reduce((sum, item) => sum + item.volume, 0),
      closed: true,
    });
  }
  return result;
}
